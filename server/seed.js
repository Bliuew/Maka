// Development-only sample data. Every row is flagged is_sample / is_placeholder
// and labelled as a sample in the app. Refused when NODE_ENV=production.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { id, now } from './db.js';
import { config } from './config.js';
import os from 'node:os';
import { processFile } from './media.js';

const run = promisify(execFile);
const scryptHash = (pw) => {
  const salt = crypto.randomBytes(16);
  return `scrypt$${salt.toString('base64')}$${crypto.scryptSync(pw, salt, 32, { N: 16384, r: 8, p: 1 }).toString('base64')}`;
};

// Sample videos are plain brand-colour gradients generated by ffmpeg: no photos,
// no people, no brands and nothing AI-generated. They exist only so the feed can be
// tried in development and are labelled as samples in the app.
async function sampleVideo(q, storage, ownerId, [c0, c1], seconds = 6) {
  const mid = id('m_');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'maka-seed-'));
  const src = path.join(dir, 'upload.part');
  await run('ffmpeg', ['-y', '-v', 'error', '-f', 'lavfi', '-i', `gradients=s=720x1280:c0=${c0}:c1=${c1}:x0=0:y0=0:x1=720:y1=1280:speed=0.012:d=${seconds}:r=25`,
    '-f', 'lavfi', '-i', 'anullsrc=r=44100:cl=stereo', '-t', String(seconds), '-c:v', 'libx264', '-preset', 'veryfast', '-pix_fmt', 'yuv420p',
    '-c:a', 'aac', '-shortest', '-f', 'mp4', src]);
  const size = fs.statSync(src).size;
  await q.run('INSERT INTO media (id,owner_id,kind,status,total_size,received,created_at) VALUES (?,?,?,?,?,?,?)', mid, ownerId, 'video', 'processing', size, size, now());
  const out = await processFile(storage, { id: mid, kind: 'video' }, src);
  fs.rmSync(dir, { recursive: true, force: true });
  await q.run('UPDATE media SET status=?, file=?, poster=?, width=?, height=?, duration=?, error=? WHERE id=?', out.status, out.file, out.poster, out.width, out.height, out.duration, out.error || null, mid);
  return mid;
}

export async function seed({ q, storage }, { adminPassword } = {}) {
  if (config.env === 'production') throw new Error('Refusing to seed sample data in production.');
  if (await q.get('SELECT 1 FROM users WHERE is_sample=1')) return { skipped: true };
  const t = now();
  const mkUser = async (handle, name, bio, avatar, role = 'user', pw = crypto.randomBytes(12).toString('hex')) => {
    const uid = id('u_');
    await q.run(`INSERT INTO users (id,email,email_norm,pass_hash,handle,display_name,bio,avatar,role,age_status,is_sample,created_at) VALUES (?,?,?,?,?,?,?,?,?,?,1,?)`,
      uid, `${handle}@sample.maka.test`, `${handle}@sample.maka.test`, scryptHash(pw), handle, name, bio, avatar, role, 'verified', t);
    return uid;
  };
  const admin = await mkUser('trust.safety', 'Mäka Trust & Safety (dev)', 'Development moderator account.', null, 'admin', adminPassword || 'dev-admin-password');
  const amara = await mkUser('amara.creates', 'Amara', 'Sample creator account.', null);
  const olivia = await mkUser('olivia.studio', 'Olivia', 'Sample creator account.', null);
  const cinema = await mkUser('maka.cinema.sample', 'Mäka Cinema', 'Sample account for the Cinema demo.', null);
  const brand = await mkUser('glow.brand.sample', 'Everyday Glow', 'Sample business account.', null);

  // A few follows so counts differ — ranking and eligibility ignore them.
  await q.run('INSERT INTO follows VALUES (?,?,?)', olivia, amara, t);
  await q.run('INSERT INTO follows VALUES (?,?,?)', cinema, amara, t);

  const posts = [
    [amara, ['0xF6C66F', '0xCF9845'], 'Sample post'],
    [olivia, ['0x1D1D21', '0xCF9845'], 'Sample post'],
    [cinema, ['0x0B0B0D', '0x6B4A1F'], 'Sample post'],
    [amara, ['0xFFF4DD', '0xF6C66F'], 'Sample post'],
  ];
  let i = 0;
  for (const [author, colours, caption] of posts) {
    const mid = await sampleVideo(q, storage, author, colours);
    await q.run(`INSERT INTO posts (id,author_id,media_id,kind,caption,status,allow_comments,remix_policy,created_at,published_at) VALUES (?,?,?,?,?,?,?,?,?,?)`,
      id('p_'), author, mid, 'video', caption, 'published', 1, 'followers', t - i * 3600e3, t - i * 3600e3);
    i++;
  }

  // Businesses (verified samples) with campaigns and products
  const mkBiz = async (owner, name, category, description) => {
    const bid = id('b_');
    await q.run('INSERT INTO businesses (id,owner_id,name,category,description,registration_ref,verification,is_sample,created_at) VALUES (?,?,?,?,?,?,?,1,?)', bid, owner, name, category, description, 'SAMPLE', 'verified', t);
    return bid;
  };
  const glow = await mkBiz(brand, 'Everyday Glow', 'Beauty', 'Sample store for trying the marketplace.');
  const sound = await mkBiz(admin, 'Sound & Style', 'Fashion', 'Sample store for trying the marketplace.');
  const indie = await mkBiz(admin, 'Indie Film Voices', 'Entertainment', 'Sample store for trying the marketplace.');
  const home = await mkBiz(admin, 'Honey & Home', 'Home & Living', 'Sample store for trying the marketplace.');
  const camp = (biz, title, cat, brief, cents) => q.run(`INSERT INTO campaigns (id,business_id,title,category,brief,deliverables,compensation_cents,currency,image,is_sample,created_at)
    VALUES (?,?,?,?,?,?,?,?,?,1,?)`, id('cp_'), biz, title, cat, brief, 'One 30 to 60 second vertical video, marked as a paid partnership.', cents, 'CAD', null, t);
  await camp(glow, 'The Everyday Glow', 'Beauty', 'A 30-second skincare story, filmed vertically.', 25000);
  await camp(sound, 'Sound & Style', 'Fashion', 'Pitch a product video concept.', 30000);
  await camp(indie, 'Indie Film Voices', 'Entertainment', 'Short original reviews of independent films.', 20000);
  const prod = (biz, name, desc, cents, stock = 25) => q.run(`INSERT INTO products (id,business_id,name,description,price_cents,currency,image,stock,is_sample,created_at) VALUES (?,?,?,?,?,?,?,?,1,?)`,
    id('pr_'), biz, name, desc, cents, 'CAD', null, stock, t);
  await prod(glow, 'Honey Glow Serum', 'Lightweight daily serum.', 3400);
  await prod(glow, 'Calm Night Balm', 'Overnight balm.', 2800);
  await prod(sound, 'Gold Thread Tote', 'Canvas tote.', 6500);
  await prod(home, 'Amber Room Spray', 'Room spray.', 2200, 0);
  await prod(indie, 'Festival Pass', 'Digital festival pass.', 1500);

  // Cinema: clearly fictional placeholder titles — no rights, no streams.
  const film = (name, kind, genres, synopsis, lang = 'en') => q.run(`INSERT INTO titles (id,name,kind,genres,language,synopsis,poster,is_placeholder,created_at) VALUES (?,?,?,?,?,?,?,1,?)`,
    id('t_'), name, kind, genres, lang, synopsis, null, t);
  await film('A Second Chance', 'movie', 'Romance,Drama', 'A sweeping story about finding connection again.');
  await film('Beyond the Horizon', 'movie', 'Adventure,Drama', 'A journey that changes everything.');
  await film('Roommates Again', 'series', 'Comedy,Friendship', 'Three friends, one unexpected reunion.');
  await film('The Golden City', 'movie', 'Mystery,Thriller', 'Every city holds a secret.', 'fr');
  return { admin: 'trust.safety@sample.maka.test' };
}
